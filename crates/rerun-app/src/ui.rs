/// Says in a plain message box, before any Slint object exists, why Rerun does not start
/// (security review S1 of P5-3: Slint reads font settings from the environment as soon as a
/// window is created). `elevated`: the process runs as administrator (or that is unknown);
/// otherwise the system layer could not be created.
pub fn refuse_start(lang: Lang, elevated: bool) {
    let (title, text) = if elevated {
        (
            t(lang, Msg::ElevatedTitle),
            format!(
                "{} {}",
                t(lang, Msg::ElevatedBody),
                t(lang, Msg::ElevatedHow)
            ),
        )
    } else {
        (
            t(lang, Msg::GuardTitle),
            t(lang, Msg::GuardBody).into_owned(),
        )
    };
    let caption = format!("{} \u{2013} {title}", t(lang, Msg::AppName));
    chrome::message_box(&caption, &text);
}

/// Runs the window until it is closed. `make` builds the worker's world on its thread, with the
/// slot the window fills with its handle once its native window exists: the owner of the UAC
/// dialog (P5-5c).
pub fn run<F>(make: F) -> ExitCode
where
    F: FnOnce(PromptOwnerSlot) -> Result<World, Shown<'static>> + Send + 'static,
{
    // The software renderer always (module docs).
    if slint::BackendSelector::new()
        .backend_name("winit".into())
        .renderer_name("software".into())
        .select()
        .is_err()
    {
        return ExitCode::FAILURE;
    }
    crate::trace::log(|| "ui: backend selected".to_owned());
    let lang = lang();
    let Ok(ui) = AppWindow::new() else {
        return ExitCode::FAILURE;
    };
    crate::trace::log(|| "ui: window object created (fonts registered)".to_owned());
    let tokens = theme::tokens(ThemeId::default());
    set_theme(&ui, &tokens);
    set_strings(&ui, lang);
    ui.set_status_index(tr(lang, Msg::StatusReading));
    if cfg!(feature = "test-key") {
        ui.set_status_build(tr(lang, Msg::TestKeyBuild));
    }

    let Ok(worker) = Worker::start(lang, make, Box::new(SlintWake(ui.as_weak()))) else {
        return ExitCode::FAILURE;
    };
    worker.send(Job::Library);
    worker.send(Job::Status);
    let state = Rc::new(RefCell::new(State {
        worker,
        lang,
        rows: Vec::new(),
        game: None,
        applied: None,
        system: None,
        page: None,
        selection: Selection::default(),
        preview_hash: None,
        game_cards: Vec::new(),
        applied_cards: Vec::new(),
        dialog: None,
        opener: -1,
        download: None,
        close_after_download: false,
        uac: false,
    }));
    callbacks(&ui, &state);

    crate::trace::log(|| "ui: window built, showing".to_owned());
    if ui.show().is_err() {
        return ExitCode::FAILURE;
    }
    crate::trace::log(|| "ui: shown, entering the event loop".to_owned());
    #[cfg(feature = "test-key")]
    slint::invoke_from_event_loop(|| crate::trace::log(|| "ui: event loop, first turn".to_owned()))
        .ok();
    install_chrome(&ui, &tokens, 0);
    hand_owner(&ui, &state, 0);
    if slint::run_event_loop().is_err() {
        return ExitCode::FAILURE;
    }
    ExitCode::SUCCESS
}

/// Hands the worker the window's handle as the owner of the UAC dialog once the native window
/// exists (it appears with the first turn of the event loop). The system reads it at every
/// helper start; after a few tries without a handle the dialog has no owner of the app's (it may
/// open behind the window) (P5-5c).
fn hand_owner(ui: &AppWindow, state: &Rc<RefCell<State>>, tries: u32) {
    let weak = ui.as_weak();
    let state = state.clone();
    slint::Timer::single_shot(
        Duration::from_millis(if tries == 0 { 0 } else { 50 }),
        move || {
            let Some(ui) = weak.upgrade() else {
                return;
            };
            match chrome::owner_of(ui.window()).and_then(PromptOwner::from_raw) {
                Some(owner) => {
                    state.borrow().worker.set_owner(Some(owner));
                }
                None if tries < 20 => hand_owner(&ui, &state, tries + 1),
                None => {}
            }
        },
    );
}

/// Installs the snap-layout subclass once the native window exists (it appears with the first
/// turn of the event loop); a few tries, then the window stays without snap layouts.
fn install_chrome(ui: &AppWindow, tokens: &Tokens, tries: u32) {
    let weak = ui.as_weak();
    let geometry = Geometry {
        title_h: tokens.title_h,
        caption_w: tokens.caption_w,
        resize_border: tokens.resize_border,
    };
    let tokens = tokens.clone();
    slint::Timer::single_shot(
        Duration::from_millis(if tries == 0 { 0 } else { 50 }),
        move || {
            let Some(ui) = weak.upgrade() else {
                return;
            };
            let w = ui.as_weak();
            let on = Box::new(move |c: Chrome| {
                if let Some(ui) = w.upgrade() {
                    match c {
                        Chrome::Hover(h) => ui.set_max_nc_hover(h),
                        Chrome::ToggleMaximized => {
                            let max = ui.window().is_maximized();
                            ui.window().set_maximized(!max);
                        }
                    }
                }
            });
            let w = ui.as_weak();
            let state = Box::new(move || match w.upgrade() {
                Some(ui) => WindowState {
                    scale: ui.window().scale_factor(),
                    maximized: ui.window().is_maximized(),
                },
                None => WindowState {
                    scale: 1.0,
                    maximized: false,
                },
            });
            if !chrome::install(ui.window(), geometry, state, on) && tries < 20 {
                install_chrome(&ui, &tokens, tries + 1);
            }
        },
    );
}

