/// The UI thread's state.
struct State {
    worker: Worker,
    lang: Lang,
    /// The library's rows, as streamed.
    rows: Vec<RowVm>,
    /// The game page last asked for.
    game: Option<u32>,
    /// The pages as last handed to the window: an unchanged page is not set again (P5-3b), so
    /// a visit that the worker answers from its session does not rebuild its models.
    applied: Option<AppliedVm>,
    system: Option<SystemVm>,
    /// The game page as handed to the window (the selection works on it).
    page: Option<GameVm>,
    /// The fixes the user selected on `page`.
    selection: Selection,
    /// The plan hash of the preview the window shows.
    preview_hash: Option<String>,
    /// The cards of the page that shows them (the game page or the applied page).
    game_cards: Vec<TxnCardVm>,
    applied_cards: Vec<TxnCardVm>,
    /// The open undo or forget dialog.
    dialog: Option<(DialogKind, TxnId, u64)>,
    /// The card button that opened it (2 * index, +1 for forget), or the checkbox of a fix
    /// (-2 - index): the focus returns there.
    opener: i32,
    /// The open download dialog (consent, progress or failure), if any.
    download: Option<DownloadState>,
    /// The window was asked to close during a download: it cancels it and closes by itself when
    /// the worker reports the end.
    close_after_download: bool,
    /// The window shows "waiting for Windows (UAC)": no button, Esc ignored, closed by the
    /// result (P5-5c).
    uac: bool,
}

/// Wakes the event loop from the worker thread (ADR 0026: `invoke_from_event_loop`).
struct SlintWake(slint::Weak<AppWindow>);

impl Wake for SlintWake {
    fn wake(&self) {
        // An error means the event loop has ended: nothing left to wake.
        let _ = self.0.upgrade_in_event_loop(|ui| ui.invoke_poll());
    }
}

