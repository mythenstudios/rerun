fn callbacks(ui: &AppWindow, state: &Rc<RefCell<State>>) {
    let weak = ui.as_weak();
    ui.global::<Reveal>().on_request(move |y, h| {
        if let Some(ui) = weak.upgrade() {
            ui.invoke_reveal(y, h);
        }
    });

    let weak = ui.as_weak();
    let st = state.clone();
    ui.on_poll(move || {
        if let Some(ui) = weak.upgrade() {
            poll(&ui, &st);
        }
    });

    let weak = ui.as_weak();
    let st = state.clone();
    ui.on_navigate(move |page| {
        let Some(ui) = weak.upgrade() else {
            return;
        };
        ui.set_page(page);
        ui.set_game_open(false);
        // No game page is open: a late preview or page for it is ignored, nothing is planned.
        let mut st = st.borrow_mut();
        st.game = None;
        st.page = None;
        match page {
            1 => st.worker.send(Job::Status),
            3 => {
                // The reading text only while there is nothing to show yet; a page seen before
                // stays on screen and is replaced only if the answer differs.
                ui.set_system_loading(st.system.is_none());
                st.worker.send(Job::System);
            }
            _ => {}
        }
    });

    let weak = ui.as_weak();
    let st = state.clone();
    ui.on_open_game(move |app_id| {
        let Some(ui) = weak.upgrade() else {
            return;
        };
        let Ok(app_id) = u32::try_from(app_id) else {
            return;
        };
        let mut st = st.borrow_mut();
        // The name as the view model holds it (escaped), not the string the UI shows.
        let name = st
            .rows
            .iter()
            .find(|r| r.app_id == app_id)
            .map(|r| r.name.clone());
        crate::trace::log(|| format!("ui: game {app_id} clicked"));
        // At once, from the library row: the title and the row's status; the worker fills in
        // the problems and fixes (P5-3b).
        let row = st.rows.iter().find(|r| r.app_id == app_id);
        let loading = vm::game_loading(app_id, name.as_ref(), row, st.lang);
        st.game = Some(app_id);
        st.page = None;
        st.selection = Selection::default();
        st.preview_hash = None;
        st.game_cards.clear();
        ui.set_preview(preview_none(0));
        ui.set_game(game(&loading, &Selection::default()));
        ui.set_game_loading(true);
        ui.set_game_open(true);
        st.worker.send(Job::Game { app_id, name });
    });

    let weak = ui.as_weak();
    let st = state.clone();
    ui.on_query_edited(move |_| {
        if let Some(ui) = weak.upgrade() {
            show_rows(&ui, &st.borrow());
        }
    });

    let weak = ui.as_weak();
    let st = state.clone();
    ui.on_group_toggled(move |_| {
        if let Some(ui) = weak.upgrade() {
            show_rows(&ui, &st.borrow());
        }
    });

    let weak = ui.as_weak();
    let st = state.clone();
    ui.on_rescan(move || {
        let Some(ui) = weak.upgrade() else {
            return;
        };
        let mut st = st.borrow_mut();
        st.rows.clear();
        ui.set_library_reading(true);
        ui.set_library_notices(model(Vec::new()));
        show_rows(&ui, &st);
        // The worker forgets what it read for the session with the scan. The pages the window
        // holds stay (no flash) and are replaced at the next visit if the answer differs.
        st.worker.send(Job::Library);
        st.worker.send(Job::Status);
    });

    write_callbacks(ui, state);
}

/// Takes every waiting event of the worker.
fn poll(ui: &AppWindow, state: &Rc<RefCell<State>>) {
    let mut st = state.borrow_mut();
    let mut rows_changed = false;
    while let Some(e) = st.worker.poll() {
        match e {
            Event::Blocked(b) => {
                if st.uac {
                    close_dialog(ui, &mut st);
                }
                ui.set_blocked(true);
                ui.set_blocked_notice(notice(&b.notice));
            }
            Event::LibraryStarted => {
                st.rows.clear();
                ui.set_library_reading(true);
                ui.set_library_notices(model(Vec::new()));
                rows_changed = true;
            }
            Event::Row(r) => {
                st.rows.push(r);
                rows_changed = true;
            }
            Event::LibraryDone(l) => {
                ui.set_library_reading(false);
                ui.set_library_summary(s(&l.summary));
                ui.set_library_notices(model(l.notices.iter().map(notice).collect()));
                ui.set_status_index(s(&l.index.status));
                ui.set_status_signature(s(&l.index.signature));
                rows_changed = true;
            }
            Event::Game(g) => {
                if st.game == Some(g.app_id) {
                    // The first page of this visit: the preselection. Later pages (after a write
                    // or a refresh) keep what is still selectable.
                    let first = st.page.is_none();
                    if first {
                        st.selection = Selection::preselected(&g);
                    } else {
                        st.selection.keep(&g);
                    }

                    let app_id = g.app_id;
                    st.game_cards = g.applied.clone();
                    ui.set_game(game(&g, &st.selection));
                    ui.set_game_loading(false);
                    st.page = Some(g);
                    // The preview of the selection, live (nothing is changed by looking).
                    plan_selection(ui, &mut st);
                    crate::trace::log(|| format!("ui: game {app_id} shown"));
                }
            }
            Event::Preview { app_id, vm } => {
                if st.game == Some(app_id) {
                    st.preview_hash = Some(vm.hash.clone());
                    ui.set_preview(preview_data(&vm, false));
                    // Handed to the window: only now may the worker take the plan as shown
                    // (`flow::shown`); it answers with `PreviewReady`, which enables "Apply".
                    st.worker.send(Job::PreviewShown {
                        hash: vm.hash.clone(),
                    });
                }
            }
            Event::PreviewReady { hash } => {
                if st.preview_hash.as_deref() == Some(hash.as_str()) {
                    let mut p = ui.get_preview();
                    p.ready = true;
                    ui.set_preview(p);
                }
            }
            Event::PreviewNone { app_id } => {
                if st.game == Some(app_id) {
                    st.preview_hash = None;
                    ui.set_preview(preview_none(0));
                }
            }
            Event::PreviewRefused { app_id, result } => {
                if st.game == Some(app_id) {
                    st.preview_hash = None;
                    ui.set_preview(preview_refused(&result));
                }
            }
            Event::WaitingForUac(u) => write::uac_wait(ui, &mut st, &u),
            Event::Dialog(d) => {
                // Replaces the wait for Windows too (an undo whose state changed meanwhile).
                st.uac = false;
                st.dialog = Some((d.kind, d.txn, d.nonce));
                ui.set_dialog(dialog_data(&d));
                ui.set_dialog_open(true);
                let m = ui.global::<Modal>();
                m.set_working(false);
                m.set_open(true);
            }
            Event::Download(d) => download_event(ui, &mut st, &d),
            Event::DownloadEnded(outcome) => {
                if download_ended(ui, &mut st, outcome) {
                    // The window was asked to close while the download ran: it has stopped.
                    let _ = ui.hide();
                }
            }
            Event::Result(r) => {
                if st.dialog.is_some() || st.uac {
                    close_dialog(ui, &mut st);
                }
                ui.global::<Modal>().set_working(false);
                if r.refresh {
                    // Written, or the game changed: the page is read again and the selection
                    // starts over.
                    st.selection = Selection::default();
                    st.preview_hash = None;
                    ui.set_preview(preview_none(0));
                }
                show_result(ui, &r);
            }
            Event::Applied(a) => {
                if st.applied.as_ref() != Some(&a) {
                    ui.set_applied(applied(&a));
                    st.applied_cards = a.cards.clone();
                    ui.set_nav_applied_count(if a.open > 0 {
                        s(a.open.to_string())
                    } else {
                        SharedString::new()
                    });
                    st.applied = Some(a);
                }
            }
            Event::System(sys) => {
                ui.set_system_loading(false);
                if st.system.as_ref() == Some(&sys) {
                    continue;
                }
                ui.set_system_lines(model(
                    sys.lines
                        .iter()
                        .map(|l| SysLineData {
                            label: s(&l.label),
                            values: model(l.values.iter().map(|v| s(v.as_str())).collect()),
                        })
                        .collect(),
                ));
                st.system = Some(sys);
            }
        }
    }
    if rows_changed {
        show_rows(ui, &st);
        ui.set_nav_library_count(s(st.rows.len().to_string()));
    }
}

/// Lays out the library's sections for the current search and grouping.
fn show_rows(ui: &AppWindow, st: &State) {
    let query = ui.get_query();
    let sections = vm::sections(&st.rows, query.as_str(), ui.get_group(), st.lang);
    let shown: usize = sections.iter().map(|x| x.rows.len()).sum();
    ui.set_shown_rows(i32::try_from(shown).unwrap_or(i32::MAX));
    ui.set_list_label(tr(st.lang, Msg::GameListLabel { shown }));
    ui.set_sections(model(
        sections
            .iter()
            .map(|sec| SectionData {
                title: s(&sec.title),
                rows: model(sec.rows.iter().map(|i| row(&st.rows[*i])).collect()),
            })
            .collect(),
    ));
}

fn badge(b: &vm::Badge) -> BadgeData {
    BadgeData {
        sym: s(b.sym.glyph()),
        word: s(&b.word),
        quiet: b.quiet,
    }
}

fn row(r: &RowVm) -> RowData {
    RowData {
        app_id: i32::try_from(r.app_id).unwrap_or(i32::MAX),
        name: shown(&r.name),
        detail: s(&r.detail),
        exe: r.exe.as_ref().map(shown).unwrap_or_default(),
        badge: badge(&r.badge),
    }
}

fn detail(d: &DetailVm) -> DetailData {
    DetailData {
        who: d.who.as_ref().map(shown).unwrap_or_default(),
        what: shown(&d.what),
    }
}

fn notice(n: &Notice) -> NoticeData {
    NoticeData {
        title: s(&n.title),
        body: s(&n.body),
        details: model(n.details.iter().map(detail).collect()),
    }
}

fn game(g: &GameVm, sel: &Selection) -> GameData {
    GameData {
        app_id: i32::try_from(g.app_id).unwrap_or(i32::MAX),
        title: shown(&g.title),
        hero_sym: s(g.hero.sym.glyph()),
        hero_line: s(&g.hero.line),
        hero_sub: g.hero.sub.as_deref().map(s).unwrap_or_default(),
        facts: model(
            g.facts
                .iter()
                .map(|f| FactData {
                    label: s(&f.label),
                    value: match &f.value {
                        Value::Text(x) => s(x),
                        Value::Shown(x) => shown(x),
                    },
                    mono: f.mono,
                })
                .collect(),
        ),
        notes: model(g.notes.iter().map(s).collect()),
        detail: g.detail.as_ref().map(shown).unwrap_or_default(),
        problems: model(
            g.problems
                .iter()
                .map(|p| ProblemData {
                    title: shown(&p.title),
                    when: badge(&p.when),
                    fixes: model(p.fixes.iter().map(shown).collect()),
                    quiet: p.quiet,
                })
                .collect(),
        ),
        fixes: model(
            g.fixes
                .iter()
                .map(|f| FixData {
                    id: shown(&f.id),
                    kind: s(&f.kind),
                    state: badge(&f.state),
                    refused: f.refused.as_deref().map(s).unwrap_or_default(),
                    refused_detail: f.refused_detail.as_ref().map(shown).unwrap_or_default(),
                    warned: f.warned.as_deref().map(s).unwrap_or_default(),
                    selectable: matches!(f.offer, vm::Offer::Selectable | vm::Offer::NeedsDownload),
                    selected: sel.contains(&f.key),
                    note: f.note.as_deref().map(s).unwrap_or_default(),
                    preselect_note: f.preselect_note.as_deref().map(s).unwrap_or_default(),
                    exclusive: model(f.exclusive.iter().map(shown).collect()),
                    solves: model(
                        f.solves
                            .iter()
                            .map(|x| SolvedData {
                                issue: shown(&x.issue),
                                when: badge(&x.when),
                                status: badge(&x.status),
                                tradeoffs: model(x.tradeoffs.iter().map(shown).collect()),
                                sources: model(x.sources.iter().map(shown).collect()),
                            })
                            .collect(),
                    ),
                })
                .collect(),
        ),
        applied: model(g.applied.iter().map(card).collect()),
        aside: model(g.aside.iter().map(detail).collect()),
    }
}

fn applied(a: &AppliedVm) -> AppliedData {
    AppliedData {
        sym: s(if a.open > 0 {
            crate::text::Sym::Applied.glyph()
        } else {
            crate::text::Sym::Open.glyph()
        }),
        title: s(&a.title),
        sub: s(&a.sub),
        detail: a.detail.as_ref().map(shown).unwrap_or_default(),
        cards: model(a.cards.iter().map(card).collect()),
    }
}
